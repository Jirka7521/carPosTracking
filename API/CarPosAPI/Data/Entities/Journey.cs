namespace CarPosAPI.Data.Entities;

/// <summary>
/// A user-made group of a device's trips — "Holidays", "Croatia 2026" — that belongs
/// to the car, so everyone with access to the device sees the same journeys.
///
/// <para>
/// Journeys nest (<see cref="ParentId"/>, at most
/// <see cref="Dtos.TripRules.MaxJourneyDepth"/> levels) and may carry a date range.
/// The range is a <b>live rule</b>: every unpinned trip starting inside
/// <c>[RangeFrom, RangeTo)</c> belongs to the innermost such journey, including trips
/// that arrive later from a device's offline backlog. Membership by range is computed
/// at query time and never written onto the trips, so editing or deleting a range can
/// never leave stale assignments behind.
/// </para>
/// Mapped by <see cref="Configurations.JourneyConfiguration"/>.
/// </summary>
public sealed class Journey
{
    /// <summary>Surrogate key (uuid, generated by the database).</summary>
    public Guid Id { get; set; }

    /// <summary>The device whose trips this journey groups (FK).</summary>
    public Guid DeviceId { get; set; }

    /// <summary>The enclosing journey, or null for a top-level one.</summary>
    public Guid? ParentId { get; set; }

    /// <summary>Display name, unique among its siblings.</summary>
    public string Name { get; set; } = string.Empty;

    /// <summary>
    /// Inclusive start of the auto-include range (UTC), or null when the journey has
    /// no range. Set together with <see cref="RangeTo"/> or not at all.
    /// </summary>
    public DateTime? RangeFrom { get; set; }

    /// <summary>Exclusive end of the auto-include range (UTC), or null.</summary>
    public DateTime? RangeTo { get; set; }

    /// <summary>When the journey was created (UTC).</summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>When the journey was last changed (UTC).</summary>
    public DateTime UpdatedAt { get; set; }
}
