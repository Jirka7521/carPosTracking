namespace CarPosAPI.Data.Entities;

/// <summary>
/// A place-based rule: every unpinned trip that starts or ends within
/// <see cref="RadiusMeters"/> of a point, and starts while the rule is in force, belongs
/// to <see cref="JourneyId"/>.
///
/// <para>
/// Like a journey's date range this is a <b>live rule</b>: membership is computed at query
/// time by the <c>trip_effective_journeys</c> view (PostGIS <c>ST_DWithin</c> against the
/// trip's start, parking and end fixes, defined once in the <c>trip_near</c> SQL function)
/// and never written onto the trips. It therefore applies to the past from
/// <see cref="ValidFrom"/>, and to trips whose data arrives late.
/// </para>
///
/// <para>
/// <b>Rules are never deleted.</b> Ending one sets <see cref="EndedAt"/>; the rule keeps
/// covering trips that started while it was in force and stays visible as history. Only
/// the erasure paths remove rows.
/// </para>
///
/// <para>
/// The database also carries a generated <c>center geography(Point,4326)</c> column,
/// deliberately absent from this model, derived from <see cref="Latitude"/> and
/// <see cref="Longitude"/> exactly like <c>positions.location</c>.
/// </para>
/// Mapped by <see cref="Configurations.JourneyLocationRuleConfiguration"/>.
/// </summary>
public sealed class JourneyLocationRule
{
    /// <summary>Surrogate key (uuid, generated by the database).</summary>
    public Guid Id { get; set; }

    /// <summary>The device whose trips the rule sorts (FK).</summary>
    public Guid DeviceId { get; set; }

    /// <summary>
    /// The journey matching trips join. Null only on an ended rule whose journey was
    /// deleted at the top level (a rule still in force was ended by that deletion).
    /// </summary>
    public Guid? JourneyId { get; set; }

    /// <summary>Optional label ("Office"); null when unnamed.</summary>
    public string? Name { get; set; }

    /// <summary>Centre latitude in decimal degrees, +N/−S.</summary>
    public double Latitude { get; set; }

    /// <summary>Centre longitude in decimal degrees, +E/−W.</summary>
    public double Longitude { get; set; }

    /// <summary>Radius of the circle in metres.</summary>
    public int RadiusMeters { get; set; }

    /// <summary>True when a trip starting inside the circle matches.</summary>
    public bool MatchStart { get; set; }

    /// <summary>True when a trip ending inside the circle matches.</summary>
    public bool MatchEnd { get; set; }

    /// <summary>The rule covers trips starting at or after this instant (UTC).</summary>
    public DateTime ValidFrom { get; set; }

    /// <summary>When the rule was ended (UTC), or null while it is in force. Exclusive.</summary>
    public DateTime? EndedAt { get; set; }

    /// <summary>
    /// Why the rule ended — one of <see cref="Dtos.LocationRuleEndReasons"/> — or null
    /// while it is in force.
    /// </summary>
    public string? EndReason { get; set; }

    /// <summary>When the rule was created (UTC).</summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>When the rule was last changed (UTC).</summary>
    public DateTime UpdatedAt { get; set; }
}
