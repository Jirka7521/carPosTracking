using CarPosAPI.Data.Entities;
using CarPosAPI.Dtos;
using Microsoft.EntityFrameworkCore;
using Microsoft.EntityFrameworkCore.Metadata.Builders;

namespace CarPosAPI.Data.Configurations;

/// <summary>
/// EF mapping for <see cref="Trip"/>. Snake_case names spelled out like every other
/// configuration. The table holds only trip starts and the user's placement of them;
/// see the entity for why nothing derived is stored.
/// </summary>
public sealed class TripConfiguration : IEntityTypeConfiguration<Trip>
{
    /// <summary>Configures the trips table.</summary>
    /// <param name="builder">Type builder supplied by EF Core.</param>
    public void Configure(EntityTypeBuilder<Trip> builder)
    {
        builder.ToTable("trips", table =>
        {
            // A journey is only ever stored as the user's explicit choice. An unpinned
            // trip's journey comes from the date ranges at query time; storing one here
            // would be a second, stale source of truth.
            table.HasCheckConstraint("ck_trips_journey_pinned", "journey_pinned OR journey_id IS NULL");

            // "No name" has one representation: NULL, never a blank string.
            table.HasCheckConstraint("ck_trips_name_not_blank", "name IS NULL OR length(btrim(name)) > 0");
        });

        builder.HasKey(trip => trip.Id);

        // long key → bigint GENERATED BY DEFAULT AS IDENTITY (Npgsql default).
        builder.Property(trip => trip.Id)
            .HasColumnName("id");

        builder.Property(trip => trip.DeviceId)
            .HasColumnName("device_id")
            .IsRequired();

        // Restrict, like positions: trips are history derived from them, and only the
        // explicit erasure paths may remove either.
        builder.HasOne<Device>()
            .WithMany()
            .HasForeignKey(trip => trip.DeviceId)
            .OnDelete(DeleteBehavior.Restrict);

        builder.Property(trip => trip.StartTime)
            .HasColumnName("start_time")
            .IsRequired();

        builder.Property(trip => trip.JourneyId)
            .HasColumnName("journey_id");

        // Restrict, not SET NULL: SET NULL would silently turn "pinned to Croatia" into
        // "pinned to no journey". JourneyService re-pins a deleted journey's trips to its
        // parent before deleting it.
        builder.HasOne<Journey>()
            .WithMany()
            .HasForeignKey(trip => trip.JourneyId)
            .OnDelete(DeleteBehavior.Restrict);

        builder.Property(trip => trip.JourneyPinned)
            .HasColumnName("journey_pinned")
            .HasDefaultValue(false)
            .IsRequired();

        builder.Property(trip => trip.Name)
            .HasColumnName("name")
            .HasMaxLength(TripRules.MaxNameLength);

        builder.Property(trip => trip.ComputedAt)
            .HasColumnName("computed_at")
            .HasDefaultValueSql("now()");

        // The list's only access path: newest first per device, keyset-paged by start.
        // Deliberately NOT unique — the worker updates starts in place inside one
        // transaction, and two rows may briefly hold the same value mid-update.
        builder.HasIndex(trip => new { trip.DeviceId, trip.StartTime })
            .IsDescending(false, true)
            .HasDatabaseName("ix_trips_device_id_start_time");

        // Serves "trips pinned to this journey" and the Restrict check when a journey is
        // deleted. Partial, because most trips are never pinned.
        builder.HasIndex(trip => trip.JourneyId)
            .HasFilter("journey_id IS NOT NULL")
            .HasDatabaseName("ix_trips_journey_id");
    }
}
